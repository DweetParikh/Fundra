use anchor_lang::prelude::*;
use anchor_spl::token::{Mint, Token, TokenAccount};
use mpl_core::instructions::CreateCollectionV2CpiBuilder;

use crate::constants::*;
use crate::errors::FundraError;
use crate::state::*;

#[derive(Accounts)]
#[instruction(campaign_id: u64)]
pub struct CreateCampaign<'info> {
    #[account(mut)]
    pub maker: Signer<'info>,

    #[account(seeds = [PLATFORM_CONFIG_SEED], bump = platform_config.bump)]
    pub platform_config: Account<'info, PlatformConfig>,

    #[account(
        init,
        payer = maker,
        space = 8 + Campaign::INIT_SPACE,
        seeds = [CAMPAIGN_SEED, maker.key().as_ref(), &campaign_id.to_le_bytes()],
        bump
    )]
    pub campaign: Box<Account<'info, Campaign>>,

    /// The single contribution currency. Must be a classic SPL Token mint (the
    /// `Account<Mint>` owner check rejects Token-2022) with no freeze authority.
    #[account(
        constraint = contribution_mint.freeze_authority.is_none() @ FundraError::MintHasFreezeAuthority
    )]
    pub contribution_mint: Box<Account<'info, Mint>>,

    /// CHECK: PDA with no data. Token authority of the vault, mint authority of the reward
    /// mint, and update authority of the Core collection. It only ever signs inside this program.
    #[account(seeds = [VAULT_AUTHORITY_SEED, campaign.key().as_ref()], bump)]
    pub vault_authority: UncheckedAccount<'info>,

    #[account(
        init,
        payer = maker,
        seeds = [VAULT_SEED, campaign.key().as_ref()],
        bump,
        token::mint = contribution_mint,
        token::authority = vault_authority
    )]
    pub vault: Box<Account<'info, TokenAccount>>,

    /// Reward mint: same decimals as the contribution mint, mint authority is the vault
    /// authority PDA, and no freeze authority.
    #[account(
        init,
        payer = maker,
        seeds = [REWARD_MINT_SEED, campaign.key().as_ref()],
        bump,
        mint::decimals = contribution_mint.decimals,
        mint::authority = vault_authority
    )]
    pub reward_mint: Box<Account<'info, Mint>>,

    /// New keypair generated by the client; becomes the per-campaign Core collection.
    #[account(mut)]
    pub core_collection: Signer<'info>,

    /// CHECK: address-constrained to the Metaplex Core program.
    #[account(address = mpl_core::ID)]
    pub mpl_core_program: UncheckedAccount<'info>,

    pub token_program: Program<'info, Token>,
    pub system_program: Program<'info, System>,
}

#[allow(clippy::too_many_arguments)]
pub fn create_campaign_handler(
    ctx: Context<CreateCampaign>,
    campaign_id: u64,
    name: String,
    uri: String,
    goal: u64,
    max_funding: u64,
    deadline: i64,
    reward_rate_numerator: u64,
    reward_rate_denominator: u64,
    milestone_percentages: Vec<u8>,
) -> Result<()> {
    require!(
        name.len() <= MAX_NAME_LEN && uri.len() <= MAX_URI_LEN,
        FundraError::StringTooLong
    );

    let now = Clock::get()?.unix_timestamp;
    let terms = validate_terms(
        now,
        goal,
        max_funding,
        deadline,
        reward_rate_numerator,
        reward_rate_denominator,
        &milestone_percentages,
    )?;


    // Core collection whose update authority is the vault authority PDA. No wallet can
    // add or change assets in it.
    let core_program = ctx.accounts.mpl_core_program.to_account_info();
    let collection = ctx.accounts.core_collection.to_account_info();
    let vault_authority = ctx.accounts.vault_authority.to_account_info();
    let maker = ctx.accounts.maker.to_account_info();
    let system_program = ctx.accounts.system_program.to_account_info();
    CreateCollectionV2CpiBuilder::new(&core_program)
        .collection(&collection)
        .update_authority(Some(&vault_authority))
        .payer(&maker)
        .system_program(&system_program)
        .name(name.clone())
        .uri(uri.clone())
        .invoke()?;

    let campaign = &mut ctx.accounts.campaign;
    campaign.maker = ctx.accounts.maker.key();
    campaign.campaign_id = campaign_id;
    campaign.contribution_mint = ctx.accounts.contribution_mint.key();
    campaign.decimals = ctx.accounts.contribution_mint.decimals;
    campaign.goal = goal;
    campaign.max_funding = max_funding;
    campaign.amount_raised = 0;
    campaign.deadline = deadline;
    campaign.status = CampaignStatus::Draft;
    campaign.reward_mint = ctx.accounts.reward_mint.key();
    campaign.reward_rate_numerator = reward_rate_numerator;
    campaign.reward_rate_denominator = reward_rate_denominator;
    campaign.reward_supply_cap = terms.reward_supply_cap;
    campaign.tokens_minted = 0;
    campaign.current_milestone = 0;
    campaign.milestone_count = terms.milestone_count;
    campaign.milestone_percentages = terms.milestone_percentages;
    campaign.funds_released = 0;
    campaign.vault = ctx.accounts.vault.key();
    campaign.core_collection = ctx.accounts.core_collection.key();
    campaign.contributor_count = 0;
    campaign.bump = ctx.bumps.campaign;
    campaign.vault_authority_bump = ctx.bumps.vault_authority;
    campaign.name = name;
    campaign.uri = uri;
    Ok(())
}
